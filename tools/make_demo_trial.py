"""Write the simulated trial that the calculator opens by default.

    ./.venv/bin/python tools/make_demo_trial.py

The file is simulated. It exists so the calculator has something to load without
a download, and it is labelled as simulated in its own comment header, in the
calculator, and in the README. It is not presented as patient data.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from ppict.simulate import TrialConfig, make_trial_data  # noqa: E402

CONFIG = TrialConfig(
    name="calculator_demo",
    seed=7,
    p=60,
    n_groups=12,
    n_active_groups=3,
    n_hist=500,
    n_unlabeled=600,
    n_treat=360,
    n_control=360,
    true_effect=0.35,
    signal_r2=0.35,
    select_q=0.10,
    select_n_perm=25,
)


def main() -> int:
    data = make_trial_data(CONFIG)
    out = ROOT / "calculator" / "data" / "simulated_trial.csv"
    out.parent.mkdir(parents=True, exist_ok=True)

    lines = [
        "# ppict calculator example dataset",
        "# generated by tools/make_demo_trial.py",
        "# simulated patients from ppict.simulate, not real trial data",
        (
            f"# config: seed={CONFIG.seed} n_treat={CONFIG.n_treat} "
            f"n_control={CONFIG.n_control} n_unlabeled={CONFIG.n_unlabeled} "
            f"true_effect={CONFIG.true_effect} signal_r2={CONFIG.signal_r2} "
            f"score_mode={CONFIG.score_mode}"
        ),
        "cohort,y,t,f",
    ]
    for i in range(data.y.size):
        lines.append(
            f"trial,{data.y[i]:.6f},{int(data.t[i])},{data.f[i]:.6f}"
        )
    for value in np.asarray(data.f_unlabeled, dtype=float):
        lines.append(f"external,,,{value:.6f}")

    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(lines) - 5} rows, {out.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
